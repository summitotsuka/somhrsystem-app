let pass = 0, fail = 0; const fails = [];
function ok(n, c, d) {
  if (c) { pass++; } else { fail++; fails.push(n + (d ? '  → ' + d : '')); }
}
function eq(n, g, w) {
  ok(n, JSON.stringify(g) === JSON.stringify(w),
     'ได้ ' + JSON.stringify(g) + ' ต้องการ ' + JSON.stringify(w));
}
function block(n, fn) {
  console.log(n);
  try { fn(); } catch (e) { fail++; fails.push(n + ' ล้มกลางคัน → ' + (e && e.message)); }
}

