function ก้อน(เริ่ม, จบ, ชื่อ) {
  const i = src.indexOf(เริ่ม);
  if (i < 0) throw new Error('หา "' + ชื่อ + '" ในไฟล์ Edge ไม่เจอ');
  const j = src.indexOf(จบ, i);
  if (j < 0) throw new Error('หาปลายของ "' + ชื่อ + '" ไม่เจอ');
  return src.slice(i, j + จบ.length);
}

